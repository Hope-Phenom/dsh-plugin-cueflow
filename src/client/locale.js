/** Format `{name}` placeholders used by the dictionaries. */
export function format(text, values = {}) {
  if (typeof text !== 'string') return String(text ?? '')
  return text.replace(/\{(\w+)\}/g, (whole, key) => (values[key] === undefined ? whole : String(values[key])))
}

/** Build a `t` function with a stable fallback to the key. */
export function makeTranslator(dicts, language = 'zh') {
  const table = dicts[language] ?? dicts.zh ?? dicts.en ?? {}
  const fallback = dicts.en ?? {}
  return (key, values) => format(table[key] ?? fallback[key] ?? key, values)
}
